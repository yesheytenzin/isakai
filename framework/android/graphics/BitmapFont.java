    private static void put(char c, int[] rows) {
        byte[] g = new byte[HEIGHT];
        for (int i = 0; i < HEIGHT; i++) g[i] = (byte) rows[i];
        GLYPHS[c - 32] = g;
    }

    /** True when the glyph for {@code codePoint} sets pixel ({@code col}, {@code row}). */
    public static boolean pixel(int codePoint, int col, int row) {
        if (col < 0 || col >= WIDTH || row < 0 || row >= HEIGHT) return false;
        byte[] g;
        if (codePoint >= 32 && codePoint <= 126) {
            g = GLYPHS[codePoint - 32];
        } else {
            g = GLYPHS['?' - 32];
        }
        if (g == null) g = GLYPHS['?' - 32];
        return ((g[row] >>> (WIDTH - 1 - col)) & 1) != 0;
    }

    /** Advance width of one character cell, in unscaled pixels. */
    public static int advance() {
        return WIDTH + 1;
    }

    /** Scale factor for a target cap height in pixels (size/7, minimum 1x). */
    public static int scaleFor(int size) {
        int scale = size / HEIGHT;
        return scale < 1 ? 1 : scale;
    }

    /** Advance width of one character cell at {@code size}. */
    public static int cellWidth(int size) {
        return advance() * scaleFor(size);
    }

    /** Width of a string at float text size (cells times code points). */
    public static float measure(String text, float size) {
        if (text == null || text.isEmpty()) return 0;
        return cellWidth(Math.max(1, (int) size)) * text.codePointCount(0, text.length());
    }
    /** Line step (cell height plus one scaled pixel of leading) at {@code size}. */
    public static int lineStep(int size) {
        int scale = scaleFor(size);
        return HEIGHT * scale + scale;
    }
